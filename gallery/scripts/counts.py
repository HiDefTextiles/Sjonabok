#!/usr/bin/env python3
"""Count the charts in the repository, so no page has to hard-code a number.

    python3 gallery/scripts/counts.py [--yaml gallery/_counts.yml] [--readme README.md]

Counts come straight from the chart files (no measuring, so this is quick):

    single     patterns/min/*.txt          one mark (0/1 charts)
    multi      patterns/colour/*.txt       several kinds of mark, not *.marks.txt
    pages      pages behind the multi-mark charts (page = name without _pN)
    alphabets  patterns/alphabets/*.txt    whole alphabet sheets
    fonts      rows of patterns/alphabets/alphabets.csv with font = yes
    charts     single + multi              Sjónabók charts without the alphabets
    total      charts + alphabets          what the gallery shows by default
    wip        patterns/books/*.txt        European books (Work in progress switch)
    books      wip per book code

--yaml writes them as Quarto metadata (`counts:`), read by gallery/_quarto.yml
through metadata-files, so the pages use {{< meta counts.total >}}.
--readme rewrites the block between <!-- counts --> and <!-- /counts -->.
"""
import argparse
import csv
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PART_RE = re.compile(r"_p\d+$")


class ChartCounts:
    def __init__(self, root=ROOT):
        p = root / "patterns"
        self.single = self.charts(p / "min")
        self.multi = self.charts(p / "colour")
        self.alphabets = self.charts(p / "alphabets")
        self.books = self.charts(p / "books")
        self.fonts = self.read_fonts(p / "alphabets" / "alphabets.csv")

    @staticmethod
    def charts(d):
        """Chart files of a folder; <chart>.marks.txt are readings, not charts."""
        return sorted(f.stem for f in d.glob("*.txt") if "." not in f.stem)

    @staticmethod
    def read_fonts(path):
        if not path.exists():
            return 0
        with open(path, newline="", encoding="utf-8") as f:
            return sum(r["font"] == "yes" for r in csv.DictReader(f))

    @staticmethod
    def book_of(name):
        return name.split("_")[0]

    def as_dict(self):
        charts = len(self.single) + len(self.multi)
        return {
            "single": len(self.single),
            "multi": len(self.multi),
            "pages": len({PART_RE.sub("", n) for n in self.multi}),
            "alphabets": len(self.alphabets),
            "fonts": self.fonts,
            "charts": charts,
            "total": charts + len(self.alphabets),
            "wip": len(self.books),
            "books": dict(sorted(Counter(map(self.book_of, self.books)).items())),
        }

    def yaml(self):
        """Flat enough to write by hand, so no PyYAML is needed."""
        lines = ["# Generated by gallery/scripts/counts.py (make counts); do not edit.", "counts:"]
        for k, v in self.as_dict().items():
            if isinstance(v, dict):
                lines.append(f"  {k}:")
                lines += [f"    {b}: {n}" for b, n in v.items()]
            else:
                lines.append(f"  {k}: {v}")
        return "\n".join(lines) + "\n"

    def readme_block(self):
        c = self.as_dict()
        return (f"The gallery shows **{c['total']}** charts from *Íslensk sjónabók*: {c['single']} one-mark "
                f"charts (`patterns/min/`), {c['multi']} multi-mark charts from {c['pages']} pages "
                f"(`patterns/colour/`) and {c['alphabets']} alphabet sheets (`patterns/alphabets/`, "
                f"{c['fonts']} of them are fonts). Another {c['wip']} charts from "
                f"{len(c['books'])} printed European books (`patterns/books/`) are work in progress, "
                f"hidden unless the *Work in progress* switch is on.")

    def update_readme(self, path):
        text = path.read_text(encoding="utf-8")
        new, n = re.subn(r"(<!-- counts -->\n).*?(<!-- /counts -->)",
                         lambda m: m[1] + self.readme_block() + "\n" + m[2], text, flags=re.S)
        if not n:
            raise SystemExit(f"{path}: no <!-- counts --> block")
        if new != text:
            path.write_text(new, encoding="utf-8")
            print(f"{path}: counts updated")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--yaml", type=Path, help="write Quarto metadata here")
    ap.add_argument("--readme", type=Path, help="rewrite the counts block of this file")
    a = ap.parse_args()
    c = ChartCounts()
    if a.yaml:
        a.yaml.write_text(c.yaml(), encoding="utf-8")
    if a.readme:
        c.update_readme(a.readme)
    if not (a.yaml or a.readme):
        print(c.yaml(), end="")


if __name__ == "__main__":
    main()
